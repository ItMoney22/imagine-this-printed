// Inline icons, so the kit has no icon-library dependency to install or match.
// All of them take className and inherit currentColor.
import React from 'react'

type IconProps = { className?: string }

const base = (d: React.ReactNode, extra?: Partial<React.SVGProps<SVGSVGElement>>) =>
  function Icon({ className }: IconProps) {
    return (
      <svg
        className={className}
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth={2}
        strokeLinecap="round"
        strokeLinejoin="round"
        aria-hidden="true"
        {...extra}
      >
        {d}
      </svg>
    )
  }

