-- Mean log-prob of a name's letter pairs, with ^ and $ marking the ends.
-- NULL when the name has fewer than 2 letters (no opinion).
create or replace function public.signup_name_score(p_name text)
returns real
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  with w as (select regexp_replace(lower(coalesce(p_name, '')), '[^a-z]', '', 'g') as letters),
  s as (select '^' || letters || '$' as s, length(letters) as n from w),
  p as (select substr(s.s, i, 2) as pair from s, generate_series(1, length(s.s) - 1) as i where s.n >= 2)
  select avg(b.logp)::real from p join public.signup_name_bigrams b on b.pair = p.pair
$$;

create or replace function public.signup_bot_verdict(p_first text, p_last text, p_email text)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
  f text := regexp_replace(lower(coalesce(p_first, '')), '[^a-z]', '', 'g');
  l text := regexp_replace(lower(coalesce(p_last, '')), '[^a-z]', '', 'g');
  e text := regexp_replace(lower(coalesce(p_email, '')), '[^a-z]', '', 'g');
  score real;
  in_email boolean;
begin
  if length(f) < 2 or length(l) < 2 then
    return jsonb_build_object('strong', false, 'weak', false, 'score', null);
  end if;
  score := (public.signup_name_score(f) + public.signup_name_score(l)) / 2;
  in_email := (length(f) >= 3 and position(f in e) > 0) or (length(l) >= 3 and position(l in e) > 0);
  return jsonb_build_object(
    'score', round(score::numeric, 3),
    'name_in_email', in_email,
    'strong', score < -3.3 and not in_email,
    'weak', score < -3.0 and not in_email
  );
end;
$$;

revoke execute on function public.signup_name_score(text) from public, anon, authenticated;
revoke execute on function public.signup_bot_verdict(text, text, text) from public, anon, authenticated;

-- 3. Flag strong new signups. Never fails a signup.
create or replace function public.flag_bot_signup()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v jsonb;
begin
  begin
    v := public.signup_bot_verdict(new.raw_user_meta_data->>'first_name', new.raw_user_meta_data->>'last_name', new.email);
    if coalesce((v->>'strong')::boolean, false) then
      update public.user_profiles
         set metadata = coalesce(metadata, '{}'::jsonb) || jsonb_build_object(
               'bot_suspect', v || jsonb_build_object('rule', 'strong', 'flagged_at', now(), 'by', 'signup trigger (task 673c0b4a)'))
       where id = new.id;
    end if;
  exception when others then
    raise log 'flag_bot_signup failed for %: %', new.id, sqlerrm;
  end;
  return new;
end;
$$;

drop trigger if exists on_auth_user_flag_bot on auth.users;
create trigger on_auth_user_flag_bot
  after insert on auth.users
  for each row execute function public.flag_bot_signup();

-- 4. Dormant gate. Only a deliberate refusal escapes; any other error lets the signup through.
create or replace function public.gate_bot_signup()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  refuse boolean := false;
begin
  begin
    if (select value #>> '{}' from public.admin_settings where key = 'signup_bot_gate') = 'block' then
      refuse := coalesce((public.signup_bot_verdict(
        new.raw_user_meta_data->>'first_name', new.raw_user_meta_data->>'last_name', new.email)->>'strong')::boolean, false);
    end if;
  exception when others then
    raise log 'gate_bot_signup check failed, letting signup through: %', sqlerrm;
    refuse := false;
  end;
  if refuse then
    raise exception 'signup refused: automated signup' using errcode = 'P0001';
  end if;
  return new;
end;
$$;

drop trigger if exists on_auth_user_gate_bot on auth.users;
create trigger on_auth_user_gate_bot
  before insert on auth.users
  for each row execute function public.gate_bot_signup();

-- 5. Backfill. An account is marked when it is a customer, not already marked, and
--   strong, OR
--   weak AND created on/after 2026-09-01 AND never signed in AND has no orders.
update public.user_profiles p
   set metadata = coalesce(p.metadata, '{}'::jsonb) || jsonb_build_object(
         'bot_suspect', v.verdict || jsonb_build_object(
           'rule', case when (v.verdict->>'strong')::boolean then 'strong' else 'weak+new+never_signed_in+no_orders' end,
           'flagged_at', now(),
           'by', 'backfill 2026-10-07 (task 673c0b4a)'))
  from (
    select u.id, u.created_at, u.last_sign_in_at,
           public.signup_bot_verdict(u.raw_user_meta_data->>'first_name', u.raw_user_meta_data->>'last_name', u.email) as verdict
      from auth.users u
  ) v
 where p.id = v.id
   and p.metadata->'bot_suspect' is null
   and coalesce(p.role, 'customer') = 'customer'
   and (
     coalesce((v.verdict->>'strong')::boolean, false)
     or (coalesce((v.verdict->>'weak')::boolean, false)
         and v.created_at >= '2026-09-01'
         and v.last_sign_in_at is null
         and not exists (select 1 from public.orders o where o.user_id = v.id))
   );
